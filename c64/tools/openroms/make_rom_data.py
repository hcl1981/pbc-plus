#!/usr/bin/env python3
"""
make_rom_data.py -- turn an OpenROMs build into core/rp2350/ROM_data.cpp.

The C64 needs BASIC, KERNAL and character ROMs. The original Commodore ROMs
are not free, so PBC C64 uses MEGA65 OpenROMs (LGPL-3.0) instead, built with
config_pbc.s (no JiffyDOS / DolphinDOS fast loaders, which would bypass the
drive emulation).

Frodo emulates drive 8 at DOS level: it does not run a 1541 CPU, it answers
IEC bus operations directly. On the original KERNAL it hooks low-level serial
routines with its extension opcode $F2. OpenROMs is laid out differently, so
this script puts $F2 traps at the entry points of OpenROMs' own IEC primitives
instead, taken from the build's symbol table:

    iec_tx_command            $F2 $20  byte in $A4 under ATN -> OutATN/OutSec
    iec_tx_byte               $F2 $21  byte in $A4, C = EOI  -> Out
    iec_rx_byte               $F2 $22  -> In, byte in A and $A4
    iec_turnaround_to_listen  $F2 $23  nothing to do at DOS level
    iec_turnaround_to_talk    $F2 $23
    iec_tx_command_finalize   $F2 $23

Each trap is followed by RTS; the handlers live in core/CPUC64.cpp.

Usage (after building OpenROMs' "custom" target with config_pbc.s copied to
src/,,config_custom.s):

    make_rom_data.py <open-roms-dir> <open-roms-commit> > ../../core/rp2350/ROM_data.cpp
"""
import re
import sys

TRAPS = [
    ("iec_tx_command", 0x20),
    ("iec_tx_byte", 0x21),
    ("iec_rx_byte", 0x22),
    ("iec_turnaround_to_listen", 0x23),
    ("iec_turnaround_to_talk", 0x23),
    ("iec_tx_command_finalize", 0x23),
]
EXPORT = ["kernalerror_DEVICE_NOT_FOUND", "chrin_keyboard_repeat",
          "chrin_keyboard_empty_line", "chrin_keyboard_read",
          "chrin_keyboard_enter", "cursor_enable"]


def symbols(path):
    syms = {}
    for line in open(path):
        m = re.match(r"\s*(\w+)\s*=\s*\$([0-9a-fA-F]+)", line)
        if m:
            syms[m.group(1)] = int(m.group(2), 16)
    return syms


def array(name, data, comment):
    out = [f"/* {comment} */", f"const uint8_t {name}[{len(data)}] __aligned(4) = {{"]
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    root, commit = sys.argv[1], sys.argv[2]
    kernal = bytearray(open(f"{root}/build/kernal_custom.rom", "rb").read())
    basic = open(f"{root}/build/basic_custom.rom", "rb").read()
    chargen = open(f"{root}/bin/chargen_openroms.rom", "rb").read()
    syms = symbols(f"{root}/build/target_custom/KERNAL_combined.sym")
    assert len(kernal) == 8192 and len(basic) == 8192 and len(chargen) == 4096

    in_rom = sorted(a for a in syms.values() if 0xE000 <= a <= 0xFFFF)
    for name, op in TRAPS:
        a = syms[name]
        nxt = next(x for x in in_rom if x > a)
        assert nxt - a >= 3, f"{name} is too short to hold a trap"
        kernal[a - 0xE000:a - 0xE000 + 3] = bytes([0xF2, op, 0x60])

    print("/*")
    print(" *  ROM_data.cpp - C64 ROMs for PBC C64: MEGA65 OpenROMs, GENERATED FILE.")
    print(" *")
    print(" *  Do not edit; regenerate with tools/openroms/make_rom_data.py.")
    print(f" *  OpenROMs commit {commit}, config tools/openroms/config_pbc.s,")
    print(" *  KERNAL patched with Frodo IEC traps (see make_rom_data.py).")
    print(" *")
    print(" *  OpenROMs: Copyright Paul Gardner-Stephen 2019, Roman Standzikowski")
    print(" *  (FeralChild64) 2019-2021, and contributors. GNU LGPL-3.0-or-later;")
    print(" *  some BASIC parts MIT (Microsoft). https://github.com/MEGA65/open-roms")
    print(" */")
    print('#include "ROM_data.h"')
    print()
    for n in EXPORT:
        print(f"/* {n} = ${syms[n]:04X} */")
    print()
    print(array("BuiltinBasicROM", basic, "BASIC $A000-$BFFF"))
    print(array("BuiltinKernalROM", bytes(kernal), "KERNAL $E000-$FFFF, with traps"))
    print(array("BuiltinCharROM", chargen, "character generator"))
    print("/* Drive ROM: never executed, Frodo emulates drive 8 at DOS level. */")
    print("const uint8_t BuiltinDriveROM[DRIVE_ROM_SIZE] __aligned(4) = { 0 };")

    # Addresses the emulator needs, as a header next to it
    with open(f"{sys.argv[3]}" if len(sys.argv) > 3 else "/dev/null", "w") as h:
        h.write("/* openroms_syms.h - GENERATED by tools/openroms/make_rom_data.py */\n")
        h.write("#ifndef OPENROMS_SYMS_H\n#define OPENROMS_SYMS_H\n")
        for n in EXPORT:
            h.write(f"#define OPENROMS_{n.upper()} 0x{syms[n]:04X}\n")
        end = next(x for x in in_rom if x > syms["cursor_enable"])
        h.write(f"#define OPENROMS_CURSOR_ENABLE_END 0x{end:04X}\n")
        h.write("#endif\n")


if __name__ == "__main__":
    main()
